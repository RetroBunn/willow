"""C code generator: turns an analyzed 68000 program into C.

Each function the analyzer found becomes one C function over an M68kContext
(runtime/include/willow/m68k.h). A function's body is every instruction it can
reach without calling: branches inside it become gotos, and transfers to
another function's start become tail calls. Code shared by several functions
is emitted into each of them.

Calls push the real return address on the emulated stack, and returns pop it
into ctx->ret. After each call the caller checks ctx->ret: if the callee came
back somewhere other than the next instruction, a per-function resume
dispatcher jumps to the matching label, or returns so the caller's caller can
check. That keeps the 68000 idioms in this game working, such as pushing a
return address with `pea` and then jumping through a table.

Addresses inside the program are emitted as BASE + offset, BASE being where the
runtime loaded it. That covers relocated operands and everything PC-relative.

Every instruction adds the cycles it would have taken on the 68000 to
ctx->cycles (timing.py). The runtime's clock runs on that count.
"""

from __future__ import annotations

from dataclasses import dataclass

from .analysis import Analysis, internal_target
from .m68k import Flow, Insn, Mode, Operand
from .timing import cycles

BITS = {"b": 8, "w": 16, "l": 32}
CTYPE = {"b": "uint8_t", "w": "uint16_t", "l": "uint32_t"}
STYPE = {"b": "int8_t", "w": "int16_t", "l": "int32_t"}
MASK = {"b": "0xFFFFFF00u", "w": "0xFFFF0000u"}
COND = {
    "t": "1", "f": "0",
    "hi": "(!ctx->c && !ctx->z)", "ls": "(ctx->c || ctx->z)",
    "cc": "!ctx->c", "cs": "ctx->c", "ne": "!ctx->z", "eq": "ctx->z",
    "vc": "!ctx->v", "vs": "ctx->v", "pl": "!ctx->n", "mi": "ctx->n",
    "ge": "(ctx->n == ctx->v)", "lt": "(ctx->n != ctx->v)",
    "gt": "(!ctx->z && ctx->n == ctx->v)", "le": "(ctx->z || ctx->n != ctx->v)",
}
SHIFTS = {"asl", "asr", "lsl", "lsr", "rol", "ror", "roxl", "roxr"}


class GenError(Exception):
    pass


@dataclass
class Generated:
    name: str
    header: str  # prototypes and the base address declaration
    functions: dict[int, str]  # function start -> C definition
    table: str  # base address definition and the address -> function table


def func_name(program: str, addr: int) -> str:
    return f"{program}_{addr:06x}"


def write(gen: Generated, directory, per_file: int = 64) -> list:
    """Write a program's C into `directory`, in chunks so they compile in parallel."""
    directory.mkdir(parents=True, exist_ok=True)
    for stale in directory.glob(f"{gen.name}_*.c"):
        stale.unlink()
    (directory / f"{gen.name}.h").write_text(gen.header, encoding="utf-8")
    files = [directory / f"{gen.name}_table.c"]
    files[0].write_text(gen.table, encoding="utf-8")
    starts = sorted(gen.functions)
    for n, i in enumerate(range(0, len(starts), per_file)):
        body = "\n".join(gen.functions[s] for s in starts[i : i + per_file])
        path = directory / f"{gen.name}_{n:03}.c"
        path.write_text(
            f"/* Generated by tools/willow/codegen.py from {gen.name}. Do not edit. */\n"
            f"#include \"{gen.name}.h\"\n\n{body}",
            encoding="utf-8",
        )
        files.append(path)
    return files


def generate(a: Analysis, file: str | None = None) -> Generated:
    p, name = a.program, a.program.name
    funcs = {}
    for start in sorted(a.functions):
        r = next(((s, e) for s, e in p.entry_ranges if s <= start < e), None)
        if r is None:
            funcs[start] = _FunctionGen(a, start).emit()
            continue
        # An entry range: one function that starts wherever it is asked to, and a named
        # entry point for each of its instructions.
        s, e = r
        thunk = f"void {func_name(name, start)}(M68kContext *ctx)\n{{\n    {name}_range_{s:06x}(ctx, 0x{start:x}u);\n}}\n"
        if start == s:
            entries = [x for x in a.functions if s <= x < e]
            funcs[start] = _FunctionGen(a, s, entries).emit() + "\n" + thunk
        else:
            funcs[start] = thunk
    protos = "\n".join(f"void {func_name(name, s)}(M68kContext *ctx);" for s in sorted(a.functions))
    protos += "".join(f"\nvoid {name}_range_{s:06x}(M68kContext *ctx, uint32_t entry);" for s, _ in p.entry_ranges)
    header = (
        f"/* Generated by tools/willow/codegen.py from {name}. Do not edit. */\n"
        f"#ifndef WILLOW_GEN_{name.upper()}_H\n#define WILLOW_GEN_{name.upper()}_H\n\n"
        "#include <stddef.h>\n#include \"willow/m68k.h\"\n\n"
        f"extern uint32_t {name}_base;\n"
        f"extern const M68kFuncEntry {name}_functions[];\n"
        f"extern const size_t {name}_function_count;\n"
        f"extern const M68kProgram {name}_program;\n\n{protos}\n\n#endif\n"
    )
    entries = "\n".join(f"    {{0x{s:06x}, {func_name(name, s)}}}," for s in sorted(a.functions))
    image = ",\n".join(
        "    " + ",".join(f"0x{b:02x}" for b in p.image[i : i + 24]) for i in range(0, len(p.image), 24)
    )
    relocs = sorted(p.relocations)
    reloc_rows = ",\n".join(
        "    " + ",".join(f"0x{r:x}" for r in relocs[i : i + 12]) for i in range(0, len(relocs), 12)
    ) or "    0"
    table = (
        f"/* Generated by tools/willow/codegen.py from {name}. Do not edit. */\n"
        f"#include \"{name}.h\"\n\n"
        f"uint32_t {name}_base;\n\n"
        f"const M68kFuncEntry {name}_functions[] = {{\n{entries}\n}};\n"
        f"const size_t {name}_function_count = sizeof {name}_functions / sizeof {name}_functions[0];\n\n"
        f"static const uint8_t image[] = {{\n{image}\n}};\n\n"
        f"static const uint32_t relocations[] = {{\n{reloc_rows}\n}};\n\n"
        f"const M68kProgram {name}_program = {{\n"
        f"    \"{file or name}\", image, sizeof image, 0x{p.bss_size:x}, 0x{p.entry:x},\n"
        f"    relocations, {len(relocs)}, {name}_functions, sizeof {name}_functions / sizeof {name}_functions[0],\n"
        f"    &{name}_base,\n}};\n"
    )
    return Generated(name, header, funcs, table)


def write_index(names: list[str], directory) -> None:
    """The list of programs the runtime links, so it can find them by file name."""
    includes = "\n".join(f'#include "{n}/{n}.h"' for n in names)
    entries = "\n".join(f"    &{n}_program," for n in names)
    (directory / "programs.c").write_text(
        "/* Generated by tools/willow/codegen.py. Do not edit. */\n"
        f"#include <stddef.h>\n{includes}\n\n"
        f"const M68kProgram *const willow_programs[] = {{\n{entries}\n}};\n"
        f"const size_t willow_program_count = {len(names)};\n",
        encoding="utf-8",
    )


def function_body(a: Analysis, start: int, through=frozenset()) -> list[int]:
    """Every instruction reachable from `start` without calling or entering another function
    (other than the entry points in `through`, which belong to the same body)."""
    body: set[int] = set()
    work = [start]
    while work:
        addr = work.pop()
        if addr in body or (addr != start and addr in a.functions and addr not in through):
            continue
        insn = a.insns.get(addr)
        if insn is None:
            raise GenError(f"{addr:#x}, reached from function {start:#x}, was never decoded")
        body.add(addr)
        if insn.flow in (Flow.NEXT, Flow.BRANCH, Flow.CALL):
            work.append(addr + insn.length)
        if insn.flow in (Flow.BRANCH, Flow.JUMP):
            target = internal_target(a.program, insn)
            if target is not None:
                work.append(target)
            elif insn.flow is Flow.JUMP and addr in a.tables:
                work.extend(a.tables[addr])
    return sorted(body)


class _FunctionGen:
    def __init__(self, a: Analysis, start: int, entries=()):
        self.a, self.p, self.start = a, a.program, start
        self.name = a.program.name
        self.entries = sorted(entries)  # for an entry range: every place it can start
        self.body = function_body(a, start, frozenset(entries))
        self.in_body = set(self.body)
        self.labels: set[int] = set()  # goto targets
        self.resume: set[int] = set()  # where a call or trap may come back to
        self.uses_resume = False
        self.lines: list[str] = []
        self.tmp = 0
        self.cur = start  # address of the instruction being emitted

    # ---- output helpers ----

    def out(self, line: str) -> None:
        if "goto resume" in line:
            self.uses_resume = True
        self.lines.append("        " + line)

    def temp(self, prefix: str = "t") -> str:
        self.tmp += 1
        return f"{prefix}{self.tmp}"

    def base(self, offset: int) -> str:
        return f"({self.name}_base + 0x{offset:x}u)"

    # ---- operands ----

    def index(self, op: Operand) -> str:
        reg = f"ctx->{'da'[op.index >> 3]}[{op.index & 7}]"
        return reg if op.index_long else f"(uint32_t)(int32_t)(int16_t){reg}"

    def address(self, op: Operand, size: str | None) -> str:
        """C expression for an operand's effective address, emitting any side effects first."""
        m, r = op.mode, op.reg
        if m is Mode.IND:
            return f"ctx->a[{r}]"
        if m in (Mode.POSTINC, Mode.PREDEC):
            step = 2 if r == 7 and size == "b" else BITS[size or "l"] // 8  # a7 stays even
            ea = self.temp("ea")
            if m is Mode.POSTINC:
                self.out(f"uint32_t {ea} = ctx->a[{r}]; ctx->a[{r}] += {step};")
            else:
                self.out(f"uint32_t {ea} = ctx->a[{r}] -= {step};")
            return ea
        if m is Mode.DISP:
            return f"(ctx->a[{r}] + 0x{op.value & 0xFFFFFFFF:x}u)"
        if m is Mode.INDEX:
            return f"(ctx->a[{r}] + 0x{op.value & 0xFFFFFFFF:x}u + {self.index(op)})"
        if m is Mode.ABSW:
            return f"0x{op.value:x}u"
        if m is Mode.ABSL:
            return self.base(op.value) if op.ext in self.p.relocations else f"0x{op.value:x}u"
        if m is Mode.PCDISP:
            return self.base(op.value)
        if m is Mode.PCINDEX:
            return f"({self.base(op.value)} + {self.index(op)})"
        raise GenError(f"{m.name} has no address")

    def immediate(self, op: Operand, size: str) -> str:
        if size == "l" and op.ext is not None and op.ext in self.p.relocations:
            return self.base(op.value)
        return f"0x{op.value & (1 << BITS[size]) - 1:x}u"

    def loc(self, op: Operand, size: str) -> tuple[str, callable]:
        """(read expression, write function) for an operand, with side effects emitted once."""
        t, m = CTYPE[size], op.mode
        if m is Mode.DREG:
            reg = f"ctx->d[{op.reg}]"
            if size == "l":
                return reg, lambda v: self.out(f"{reg} = {v};")
            return f"({t}){reg}", lambda v: self.out(f"{reg} = ({reg} & {MASK[size]}) | ({t})({v});")
        if m is Mode.AREG:
            reg = f"ctx->a[{op.reg}]"
            return f"({t}){reg}", lambda v: self.out(f"{reg} = {v};")
        if m is Mode.IMM:
            return self.immediate(op, size), None
        ea = self.address(op, size)
        if not ea.isidentifier():  # pin the address so a read-modify-write computes it once
            pinned = self.temp("ea")
            self.out(f"uint32_t {pinned} = {ea};")
            ea = pinned
        bits = BITS[size]
        return f"m68k_read{bits}({ea})", lambda v: self.out(f"m68k_write{bits}({ea}, {v});")

    def read(self, op: Operand, size: str) -> str:
        """Read an operand into a fresh temporary, so reads happen in program order."""
        expr, _ = self.loc(op, size)
        if op.mode in (Mode.IMM, Mode.DREG, Mode.AREG):
            return expr
        v = self.temp("v")
        self.out(f"{CTYPE[size]} {v} = {expr};")
        return v

    def sext32(self, value: str, size: str) -> str:
        return value if size == "l" else f"(uint32_t)(int32_t)({STYPE[size]}){value}"

    # ---- control flow ----

    def goto_or_tail(self, target: int) -> None:
        if target in self.in_body:
            self.labels.add(target)
            if target <= self.cur:  # a loop: give pending interrupts their chance
                self.out(f"M68K_POLL(ctx, {self.base(target)});")
            self.out(f"goto L_{target:06x};")
        elif target in self.a.functions:
            self.out(f"{func_name(self.name, target)}(ctx);")
            self.out("goto resume;")
        else:
            raise GenError(f"{target:#x} is neither in function {self.start:#x} nor a function start")

    def after_call(self, insn: Insn) -> None:
        nxt = insn.addr + insn.length
        self.resume.add(nxt)
        self.out(f"if (ctx->ret != {self.base(nxt)}) goto resume;")

    def ret_addr(self, insn: Insn) -> str:
        return self.base(insn.addr + insn.length)

    def computed_target(self, insn: Insn) -> str:
        """Address of a jmp/jsr target that is not static."""
        t = self.temp("to")
        self.out(f"uint32_t {t} = {self.address(insn.operands[0], None)};")
        return t

    def table_switch(self, insn: Insn, target: str, call: bool) -> None:
        self.out(f"switch ({target} - {self.name}_base) {{")
        for entry in sorted(set(self.a.tables[insn.addr])):
            if call:
                self.out(f"case 0x{entry:x}u: {func_name(self.name, entry)}(ctx); break;")
            elif entry in self.in_body:
                self.labels.add(entry)
                self.out(f"case 0x{entry:x}u: goto L_{entry:06x};")
            else:
                self.out(f"case 0x{entry:x}u: {func_name(self.name, entry)}(ctx); goto resume;")
        self.out(f"default: m68k_jump(ctx, {target}); {'break' if call else 'goto resume'};")
        self.out("}")

    # ---- the function ----

    def emit(self) -> str:
        blocks = []
        for i, addr in enumerate(self.body):
            insn = self.a.insns[addr]
            self.lines, self.cur = [], addr
            if n := cycles(insn):
                self.out(f"ctx->cycles += {n};")
            self.instruction(insn)
            if insn.flow in (Flow.NEXT, Flow.BRANCH, Flow.CALL) and not self.ends_flow(insn):
                nxt = addr + insn.length
                if i + 1 >= len(self.body) or self.body[i + 1] != nxt:
                    self.goto_or_tail(nxt)
            blocks.append((addr, insn, self.lines))
            if insn.op == "pea":
                # A pushed return address, for code that calls by jumping.
                op = insn.operands[0]
                if op.mode is Mode.PCDISP or (op.mode is Mode.ABSL and op.ext in self.p.relocations):
                    if op.value in self.in_body or op.value in self.a.functions:
                        self.resume.add(op.value)
        if self.uses_resume:
            self.labels |= self.resume & self.in_body
        if self.entries:
            out = [f"void {self.name}_range_{self.start:06x}(M68kContext *ctx, uint32_t entry)", "{",
                   f"    M68K_POLL(ctx, {self.name}_base + entry);", "    switch (entry) {"]
            for e in self.entries:
                self.labels.add(e)
                out.append(f"    case 0x{e:x}u: goto L_{e:06x};")
            out.append("    }")
        else:
            out = [f"void {func_name(self.name, self.start)}(M68kContext *ctx)", "{",
                   f"    M68K_POLL(ctx, {self.base(self.start)});"]
            if self.body[0] != self.start:  # blocks are laid out by address; code before the entry is a loop
                self.labels.add(self.start)
                out.append(f"    goto L_{self.start:06x};")
        for addr, insn, lines in blocks:
            if addr in self.labels:
                out.append(f"L_{addr:06x}:;")
            out.append(f"    {{ /* {addr:06x}  {insn} */")
            out.extend(lines)
            out.append("    }")
        out.append("    return;")
        if self.uses_resume:
            out.append("resume:")
            out.append(f"    switch (ctx->ret - {self.name}_base) {{")
            for r in sorted(self.resume):
                if r in self.in_body:
                    out.append(f"    case 0x{r:x}u: goto L_{r:06x};")
                elif r in self.a.functions:  # the code after a call falls into another function
                    out.append(f"    case 0x{r:x}u: {func_name(self.name, r)}(ctx); goto resume;")
            out.append("    default: return;")
            out.append("    }")
        out.append("}")
        return "\n".join(out) + "\n"

    def ends_flow(self, insn: Insn) -> bool:
        """Instructions whose generated code never falls through, despite their flow class."""
        return insn.op == "dos" and insn.flow is Flow.STOP

    # ---- instructions ----

    def instruction(self, insn: Insn) -> None:
        op, size, ops = insn.op, insn.size, insn.operands
        handler = getattr(self, f"op_{op}", None)
        if handler is not None:
            handler(insn, size, ops)
        elif op in SHIFTS:
            self.op_shift(insn, size, ops)
        else:
            raise GenError(f"no C semantics for {op} at {insn.addr:#x}")

    def flags(self, size: str, value: str) -> None:
        self.out(f"m68k_logic{BITS[size]}(ctx, {value});")

    # moves

    def op_move(self, insn, size, ops):
        src, dst = ops
        if src.mode is Mode.SR:
            _, write = self.loc(dst, "w")
            write("m68k_get_sr(ctx)")
            return
        if dst.mode in (Mode.SR, Mode.CCR):
            v = self.read(src, "w")
            self.out(f"m68k_set_sr(ctx, {v});" if dst.mode is Mode.SR else f"m68k_set_ccr(ctx, (uint8_t){v});")
            return
        if dst.mode is Mode.USP:
            self.out(f"ctx->other_sp = ctx->a[{src.reg}];")
            return
        if src.mode is Mode.USP:
            self.out(f"ctx->a[{dst.reg}] = ctx->other_sp;")
            return
        v = self.read(src, size)
        if src.mode in (Mode.DREG, Mode.AREG):
            pinned = self.temp("v")
            self.out(f"{CTYPE[size]} {pinned} = {v};")
            v = pinned
        _, write = self.loc(dst, size)
        write(v)
        self.flags(size, v)

    def op_movea(self, insn, size, ops):
        v = self.read(ops[0], size)
        self.out(f"ctx->a[{ops[1].reg}] = {self.sext32(v, size)};")

    def op_moveq(self, insn, size, ops):
        self.out(f"ctx->d[{ops[1].reg}] = 0x{ops[0].value & 0xFFFFFFFF:x}u;")
        self.flags("l", f"ctx->d[{ops[1].reg}]")

    def op_lea(self, insn, size, ops):
        self.out(f"ctx->a[{ops[1].reg}] = {self.address(ops[0], None)};")

    def op_pea(self, insn, size, ops):
        self.out(f"m68k_push32(ctx, {self.address(ops[0], None)});")

    def op_clr(self, insn, size, ops):
        _, write = self.loc(ops[0], size)
        write("0")
        self.out("ctx->n = 0; ctx->z = 1; ctx->v = 0; ctx->c = 0;")

    def op_tst(self, insn, size, ops):
        self.flags(size, self.read(ops[0], size))

    def op_exg(self, insn, size, ops):
        x, y = (f"ctx->{'d' if o.mode is Mode.DREG else 'a'}[{o.reg}]" for o in ops)
        t = self.temp()
        self.out(f"uint32_t {t} = {x}; {x} = {y}; {y} = {t};")

    def op_swap(self, insn, size, ops):
        reg = f"ctx->d[{ops[0].reg}]"
        self.out(f"{reg} = {reg} >> 16 | {reg} << 16;")
        self.flags("l", reg)

    def op_ext(self, insn, size, ops):
        reg = f"ctx->d[{ops[0].reg}]"
        if size == "w":
            self.out(f"{reg} = ({reg} & 0xFFFF0000u) | (uint16_t)(int16_t)(int8_t){reg};")
            self.flags("w", f"(uint16_t){reg}")
        else:
            self.out(f"{reg} = (uint32_t)(int32_t)(int16_t){reg};")
            self.flags("l", reg)

    def op_movem(self, insn, size, ops):
        step = BITS[size] // 8
        regs = lambda mask: [f"ctx->{'da'[n >> 3]}[{n & 7}]" for n in range(16) if mask >> n & 1]
        if ops[0].mode is Mode.REGLIST:
            mask, dst = ops[0].reg, ops[1]
            if dst.mode is Mode.PREDEC:
                # Stored from a7 down to d0; a stored An is its value before the instruction.
                an = f"ctx->a[{dst.reg}]"
                ea, orig = self.temp("ea"), self.temp()
                if an in regs(mask):
                    self.out(f"uint32_t {orig} = {an};")
                self.out(f"uint32_t {ea} = {an};")
                for reg in reversed(regs(mask)):
                    value = orig if reg == an else reg
                    self.out(f"{ea} -= {step}; m68k_write{BITS[size]}({ea}, ({CTYPE[size]}){value});")
                self.out(f"{an} = {ea};")
            else:
                ea = self.temp("ea")
                self.out(f"uint32_t {ea} = {self.address(dst, size)};")
                for reg in regs(mask):
                    self.out(f"m68k_write{BITS[size]}({ea}, ({CTYPE[size]}){reg}); {ea} += {step};")
            return
        src, mask = ops[0], ops[1].reg
        ea = self.temp("ea")
        an = f"ctx->a[{src.reg}]"
        self.out(f"uint32_t {ea} = {an if src.mode is Mode.POSTINC else self.address(src, size)};")
        for reg in regs(mask):
            value = f"m68k_read{BITS[size]}({ea})"
            self.out(f"{reg} = {self.sext32(value, size)}; {ea} += {step};")
        if src.mode is Mode.POSTINC:
            self.out(f"{an} = {ea};")

    def op_movep(self, insn, size, ops):
        count = 2 if size == "w" else 4
        ea = self.temp("ea")
        if ops[0].mode is Mode.DREG:  # register to memory, high byte first, every other address
            reg, mem = f"ctx->d[{ops[0].reg}]", ops[1]
            self.out(f"uint32_t {ea} = {self.address(mem, size)};")
            for k in range(count):
                self.out(f"m68k_write8({ea} + {2 * k}, (uint8_t)({reg} >> {8 * (count - 1 - k)}));")
        else:
            mem, reg = ops[0], f"ctx->d[{ops[1].reg}]"
            self.out(f"uint32_t {ea} = {self.address(mem, size)};")
            parts = []
            for k in range(count):  # one byte per statement, so the reads happen in order
                b = self.temp("b")
                self.out(f"uint32_t {b} = m68k_read8({ea} + {2 * k});")
                parts.append(f"{b} << {8 * (count - 1 - k)}")
            parts = " | ".join(parts)
            if size == "w":
                self.out(f"{reg} = ({reg} & 0xFFFF0000u) | ({parts});")
            else:
                self.out(f"{reg} = {parts};")

    # arithmetic

    def arith(self, name: str, size: str, src: Operand, dst: Operand) -> None:
        bits = BITS[size]
        s = self.read(src, size)  # the source is always fetched first
        d, write = self.loc(dst, size)
        if name == "cmp":
            self.out(f"m68k_cmp{bits}(ctx, {s}, {d});")
            return
        r = self.temp("r")
        self.out(f"{CTYPE[size]} {r} = m68k_{name}{bits}(ctx, {s}, {d});")
        write(r)

    def op_add(self, insn, size, ops):
        self.arith("add", size, *ops)

    def op_sub(self, insn, size, ops):
        self.arith("sub", size, *ops)

    def op_cmp(self, insn, size, ops):
        self.arith("cmp", size, *ops)

    op_addi = op_add
    op_subi = op_sub
    op_cmpi = op_cmp

    def op_cmpm(self, insn, size, ops):
        s = self.read(ops[0], size)
        d = self.read(ops[1], size)
        self.out(f"m68k_cmp{BITS[size]}(ctx, {s}, {d});")

    def op_addq(self, insn, size, ops):
        if ops[1].mode is Mode.AREG:  # whole register, no condition codes
            self.out(f"ctx->a[{ops[1].reg}] += {ops[0].value};")
        else:
            self.arith("add", size, *ops)

    def op_subq(self, insn, size, ops):
        if ops[1].mode is Mode.AREG:
            self.out(f"ctx->a[{ops[1].reg}] -= {ops[0].value};")
        else:
            self.arith("sub", size, *ops)

    def op_adda(self, insn, size, ops):
        self.out(f"ctx->a[{ops[1].reg}] += {self.sext32(self.read(ops[0], size), size)};")

    def op_suba(self, insn, size, ops):
        self.out(f"ctx->a[{ops[1].reg}] -= {self.sext32(self.read(ops[0], size), size)};")

    def op_cmpa(self, insn, size, ops):
        s = self.sext32(self.read(ops[0], size), size)
        self.out(f"m68k_cmp32(ctx, {s}, ctx->a[{ops[1].reg}]);")

    def extended(self, name: str, size: str, ops) -> None:
        """addx, subx, abcd, sbcd: registers, or predecrement memory to memory."""
        s = self.read(ops[0], size)
        d, write = self.loc(ops[1], size)
        dv = self.temp("v")
        self.out(f"{CTYPE[size]} {dv} = {d};")
        r = self.temp("r")
        call = f"m68k_{name}(ctx, {s}, {dv})" if name in ("abcd", "sbcd") else f"m68k_{name}{BITS[size]}(ctx, {s}, {dv})"
        self.out(f"{CTYPE[size]} {r} = {call};")
        write(r)

    def op_addx(self, insn, size, ops):
        self.extended("addx", size, ops)

    def op_subx(self, insn, size, ops):
        self.extended("subx", size, ops)

    def op_abcd(self, insn, size, ops):
        self.extended("abcd", "b", ops)

    def op_sbcd(self, insn, size, ops):
        self.extended("sbcd", "b", ops)

    def unary(self, insn, size, ops, expr: str) -> None:
        d, write = self.loc(ops[0], size)
        dv, r = self.temp("v"), self.temp("r")
        self.out(f"{CTYPE[size]} {dv} = {d};")
        self.out(f"{CTYPE[size]} {r} = {expr.format(d=dv, bits=BITS[size])};")
        write(r)
        return r

    def op_neg(self, insn, size, ops):
        self.unary(insn, size, ops, "m68k_sub{bits}(ctx, {d}, 0)")

    def op_negx(self, insn, size, ops):
        self.unary(insn, size, ops, "m68k_subx{bits}(ctx, {d}, 0)")

    def op_nbcd(self, insn, size, ops):
        self.unary(insn, "b", ops, "m68k_nbcd(ctx, {d})")

    def op_not(self, insn, size, ops):
        r = self.unary(insn, size, ops, f"({CTYPE[size]})~{{d}}")
        self.flags(size, r)

    def logic(self, op: str, size: str, src: Operand, dst: Operand) -> None:
        if dst.mode in (Mode.SR, Mode.CCR):
            s = self.immediate(src, size)
            if dst.mode is Mode.SR:
                self.out(f"m68k_set_sr(ctx, (uint16_t)(m68k_get_sr(ctx) {op} {s}));")
            else:
                self.out(f"m68k_set_ccr(ctx, (uint8_t)(m68k_get_sr(ctx) {op} {s}));")
            return
        s = self.read(src, size)
        d, write = self.loc(dst, size)
        r = self.temp("r")
        self.out(f"{CTYPE[size]} {r} = ({CTYPE[size]})({d} {op} {s});")
        write(r)
        self.flags(size, r)

    def op_and(self, insn, size, ops):
        self.logic("&", size, *ops)

    def op_or(self, insn, size, ops):
        self.logic("|", size, *ops)

    def op_eor(self, insn, size, ops):
        self.logic("^", size, *ops)

    op_andi = op_and
    op_ori = op_or
    op_eori = op_eor

    def op_mulu(self, insn, size, ops):
        s = self.read(ops[0], "w")
        self.out(f"ctx->cycles += 2 * m68k_bits16({s});")
        self.out(f"ctx->d[{ops[1].reg}] = m68k_mulu(ctx, {s}, (uint16_t)ctx->d[{ops[1].reg}]);")

    def op_muls(self, insn, size, ops):
        s = self.read(ops[0], "w")
        self.out(f"ctx->cycles += 2 * m68k_bits16((uint16_t)({s} ^ {s} << 1));  /* each change between 0 and 1 */")
        self.out(f"ctx->d[{ops[1].reg}] = m68k_muls(ctx, {s}, (uint16_t)ctx->d[{ops[1].reg}]);")

    def division(self, insn, ops, name: str) -> None:
        s = self.read(ops[0], "w")
        self.out(f"if (m68k_{name}(ctx, &ctx->d[{ops[1].reg}], {s}) < 0) {{")
        self.out(f"    m68k_exception(ctx, 5, {self.ret_addr(insn)});")
        self.resume.add(insn.addr + insn.length)
        self.out(f"    if (ctx->ret != {self.ret_addr(insn)}) goto resume;")
        self.out("}")

    def op_divu(self, insn, size, ops):
        self.division(insn, ops, "divu")

    def op_divs(self, insn, size, ops):
        self.division(insn, ops, "divs")

    def op_shift(self, insn, size, ops):
        if len(ops) == 1:  # memory, by one bit
            d, write = self.loc(ops[0], "w")
            dv, r = self.temp("v"), self.temp("r")
            self.out(f"uint16_t {dv} = {d};")
            self.out(f"uint16_t {r} = m68k_{insn.op}16(ctx, {dv}, 1);")
            write(r)
            return
        count = f"{ops[0].value}" if ops[0].mode is Mode.IMM else f"ctx->d[{ops[0].reg}]"
        if ops[0].mode is not Mode.IMM:
            self.out(f"ctx->cycles += 2 * ({count} & 63);")
        d, write = self.loc(ops[1], size)
        r = self.temp("r")
        self.out(f"{CTYPE[size]} {r} = m68k_{insn.op}{BITS[size]}(ctx, {d}, {count});")
        write(r)

    # bits

    def bitop(self, insn, size, ops, change: str | None) -> None:
        num, dst = ops
        width = 31 if dst.mode is Mode.DREG else 7
        bit = self.temp("bit")
        number = f"{num.value}" if num.mode is Mode.IMM else f"ctx->d[{num.reg}]"
        self.out(f"unsigned {bit} = ({number}) & {width};")
        sz = "l" if dst.mode is Mode.DREG else "b"
        d, write = self.loc(dst, sz)
        dv = self.temp("v")
        self.out(f"{CTYPE[sz]} {dv} = {d};")
        self.out(f"ctx->z = !(({dv} >> {bit}) & 1);")
        if change:
            write(f"({CTYPE[sz]})({dv} {change.format(bit=bit)})")

    def op_btst(self, insn, size, ops):
        self.bitop(insn, size, ops, None)

    def op_bchg(self, insn, size, ops):
        self.bitop(insn, size, ops, "^ (1u << {bit})")

    def op_bclr(self, insn, size, ops):
        self.bitop(insn, size, ops, "& ~(1u << {bit})")

    def op_bset(self, insn, size, ops):
        self.bitop(insn, size, ops, "| (1u << {bit})")

    def op_scc(self, insn, size, ops):
        _, write = self.loc(ops[0], "b")
        write(f"{COND[insn.cond]} ? 0xFF : 0x00")

    def op_tas(self, insn, size, ops):
        d, write = self.loc(ops[0], "b")
        dv = self.temp("v")
        self.out(f"uint8_t {dv} = {d};")
        self.flags("b", dv)
        write(f"(uint8_t)({dv} | 0x80)")

    def op_chk(self, insn, size, ops):
        s = self.read(ops[0], "w")
        reg = f"(int16_t)ctx->d[{ops[1].reg}]"
        self.out(f"if ({reg} < 0 || {reg} > (int16_t){s}) {{")
        self.out(f"    ctx->n = {reg} < 0;")
        self.out(f"    m68k_exception(ctx, 6, {self.ret_addr(insn)});")
        self.resume.add(insn.addr + insn.length)
        self.out(f"    if (ctx->ret != {self.ret_addr(insn)}) goto resume;")
        self.out("}")

    # control flow

    def op_bra(self, insn, size, ops):
        self.goto_or_tail(insn.target)

    def op_bcc(self, insn, size, ops):
        self.out(f"if ({COND[insn.cond]}) {{")
        self.out("ctx->cycles += 10;")
        self.goto_or_tail(insn.target)
        self.out("}")
        self.out(f"ctx->cycles += {8 if insn.length == 2 else 12};")  # not taken: the short form is quicker

    def op_dbcc(self, insn, size, ops):
        reg = f"ctx->d[{ops[0].reg}]"
        self.out(f"if ({COND[insn.cond]}) {{")
        self.out("    ctx->cycles += 12;")
        self.out("} else {")
        self.out(f"    {reg} = ({reg} & 0xFFFF0000u) | (uint16_t)({reg} - 1);")
        self.out(f"    if ((uint16_t){reg} != 0xFFFF) {{")
        self.out("        ctx->cycles += 10;")
        self.goto_or_tail(insn.target)
        self.out("    }")
        self.out("    ctx->cycles += 14;")
        self.out("}")

    def op_bsr(self, insn, size, ops):
        self.out(f"m68k_push32(ctx, {self.ret_addr(insn)});")
        self.out(f"{func_name(self.name, insn.target)}(ctx);")
        self.after_call(insn)

    def op_jsr(self, insn, size, ops):
        target = internal_target(self.p, insn)
        if target is not None:
            self.op_bsr(insn, size, ops)
            return
        to = self.computed_target(insn)
        self.out(f"m68k_push32(ctx, {self.ret_addr(insn)});")
        if insn.addr in self.a.tables:
            self.table_switch(insn, to, call=True)
        else:
            self.out(f"m68k_jump(ctx, {to});")
        self.after_call(insn)

    def op_jmp(self, insn, size, ops):
        target = internal_target(self.p, insn)
        if target is not None:
            self.goto_or_tail(target)
            return
        to = self.computed_target(insn)
        if insn.addr in self.a.tables:
            self.table_switch(insn, to, call=False)
        else:
            self.out(f"m68k_jump(ctx, {to});")
            self.out("goto resume;")

    # Returns go through the resume dispatcher: the address popped may be a label in this
    # very function, when the code "called" by pushing a return address and jumping.

    def op_rts(self, insn, size, ops):
        self.out("ctx->ret = m68k_pop32(ctx);")
        self.out("goto resume;")

    def op_rte(self, insn, size, ops):
        self.out("uint16_t sr = m68k_read16(ctx->a[7]);")
        self.out("ctx->ret = m68k_read32(ctx->a[7] + 2);")
        self.out("ctx->a[7] += 6;")
        self.out("m68k_set_sr(ctx, sr);")
        self.out("goto resume;")

    def op_rtr(self, insn, size, ops):
        self.out("m68k_set_ccr(ctx, (uint8_t)m68k_read16(ctx->a[7]));")
        self.out("ctx->ret = m68k_read32(ctx->a[7] + 2);")
        self.out("ctx->a[7] += 6;")
        self.out("goto resume;")

    def op_trap(self, insn, size, ops):
        self.out(f"m68k_trap(ctx, {ops[0].value}, {self.ret_addr(insn)});")
        self.after_call(insn)

    def op_trapv(self, insn, size, ops):
        self.out("if (ctx->v) {")
        self.out(f"    m68k_exception(ctx, 7, {self.ret_addr(insn)});")
        self.resume.add(insn.addr + insn.length)
        self.out(f"    if (ctx->ret != {self.ret_addr(insn)}) goto resume;")
        self.out("}")

    def op_illegal(self, insn, size, ops):
        self.out(f"m68k_exception(ctx, 4, {self.ret_addr(insn)});")
        self.out("goto resume;")

    def op_dos(self, insn, size, ops):
        self.out(f"m68k_line_f(ctx, 0xFF{ops[0].value:02X}, {self.ret_addr(insn)});")
        if insn.flow is Flow.STOP:
            self.out("return;")
        else:
            self.after_call(insn)

    def op_fefunc(self, insn, size, ops):
        self.out(f"m68k_line_f(ctx, 0xFE{ops[0].value:02X}, {self.ret_addr(insn)});")
        self.after_call(insn)

    def op_link(self, insn, size, ops):
        an = f"ctx->a[{ops[0].reg}]"
        self.out(f"m68k_push32(ctx, {an});")
        self.out(f"{an} = ctx->a[7];")
        self.out(f"ctx->a[7] += (uint32_t)(int32_t)(int16_t)0x{ops[1].value:x};")

    def op_unlk(self, insn, size, ops):
        an = f"ctx->a[{ops[0].reg}]"
        self.out(f"ctx->a[7] = {an};")
        self.out(f"{an} = m68k_pop32(ctx);")

    def op_nop(self, insn, size, ops):
        self.out(";")

    def op_stop(self, insn, size, ops):
        self.out(f"m68k_stop(ctx, 0x{ops[0].value:x});")

    def op_reset(self, insn, size, ops):
        self.out("m68k_reset(ctx);")
